import { mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import type { INestApplication } from '@nestjs/common';
import { Test } from '@nestjs/testing';
import { AppModule } from '../src/app.module.js';
import {
  EMBEDDING_PROVIDER,
  type EmbeddingProvider,
} from '../src/embeddings/embedding-provider.js';
import { IndexingService } from '../src/indexing/indexing.service.js';
import { MeetingsService } from '../src/meetings/meetings.service.js';
import { RetrievalService } from '../src/retrieval/retrieval.service.js';
import {
  SEARCH_MODES,
  type SearchHit,
  type SearchMode,
} from '../src/retrieval/retrieval.types.js';
import { RETRIEVAL_CASES, type RetrievalCase } from './retrieval-cases.js';

/**
 * Retrieval quality on the sample meetings, with the real embedding model.
 * Needs Postgres and Ollama: `npm run deps:up`, then `npm run eval:retrieval`.
 *
 * Writes eval/results/retrieval.md. That file is committed on purpose: its
 * diff shows how a change affected retrieval quality. The thresholds are a
 * floor just under the measured baseline, so a regression fails loudly.
 */
const TOP_K = 8;
const MIN_HYBRID = { hitAt3: 0.85, mrr: 0.7 };

const SAMPLES = join(import.meta.dirname, '../../../samples/transcripts');
const REPORT = join(import.meta.dirname, 'results', 'retrieval.md');

interface Metrics {
  hitAt1: number;
  hitAt3: number;
  mrr: number;
  /** Questions whose relevant chunk wasn't in the top 3, with its rank. */
  misses: string[];
}

describe('retrieval quality (real embeddings)', () => {
  let app: INestApplication;
  const results = new Map<SearchMode, Metrics>();

  beforeAll(async () => {
    const moduleRef = await Test.createTestingModule({
      imports: [AppModule],
    }).compile();
    app = moduleRef.createNestApplication();
    await app.init();

    const meetings = app.get(MeetingsService);
    for (const file of readdirSync(SAMPLES)) {
      await meetings.ingest({
        content: readFileSync(join(SAMPLES, file), 'utf8'),
        filename: file,
      });
    }
    await app.get(IndexingService).whenIdle();
  });

  afterAll(async () => {
    await app?.close();
  });

  it.each(SEARCH_MODES)('measures %s retrieval', async (mode) => {
    const retrieval = app.get(RetrievalService);
    const ranks: (number | null)[] = [];
    for (const testCase of RETRIEVAL_CASES) {
      const { hits } = await retrieval.search({
        query: testCase.question,
        mode,
        limit: TOP_K,
      });
      ranks.push(firstRelevantRank(hits, testCase));
    }
    results.set(mode, metrics(ranks));
  });

  it('hybrid retrieval meets the quality floor', () => {
    writeReport(results, app.get<EmbeddingProvider>(EMBEDDING_PROVIDER).model);

    const hybrid = results.get('hybrid');
    expect(hybrid?.hitAt3).toBeGreaterThanOrEqual(MIN_HYBRID.hitAt3);
    expect(hybrid?.mrr).toBeGreaterThanOrEqual(MIN_HYBRID.mrr);
  });
});

/** 1-based rank of the first relevant hit, or null if none in the top K. */
function firstRelevantRank(hits: SearchHit[], c: RetrievalCase): number | null {
  const index = hits.findIndex(
    (h) =>
      h.meetingTitle.toLowerCase().includes(c.meeting) &&
      h.content.toLowerCase().includes(c.evidence.toLowerCase()),
  );
  return index === -1 ? null : index + 1;
}

function metrics(ranks: (number | null)[]): Metrics {
  const n = ranks.length;
  return {
    hitAt1: ranks.filter((r) => r === 1).length / n,
    hitAt3: ranks.filter((r) => r !== null && r <= 3).length / n,
    mrr: ranks.reduce<number>((sum, r) => sum + (r ? 1 / r : 0), 0) / n,
    misses: RETRIEVAL_CASES.flatMap((c, i) => {
      const rank = ranks[i];
      return rank === null || rank > 3
        ? [`${c.question} (rank ${rank ?? 'not in top ' + TOP_K})`]
        : [];
    }),
  };
}

function writeReport(results: Map<SearchMode, Metrics>, model: string): void {
  const pct = (x: number) => `${Math.round(x * 100)}%`;
  const code = (s: string | number) => '`' + String(s) + '`';
  const lines = [
    '# Retrieval eval',
    '',
    `${RETRIEVAL_CASES.length} questions over ${code('samples/transcripts')}, ` +
      `top ${TOP_K} hits, embedding model ${code(model)}. ` +
      `Generated by ${code('npm run eval:retrieval')}.`,
    '',
    '| Mode | hit@1 | hit@3 | MRR |',
    '| ---- | ----- | ----- | --- |',
    ...[...results].map(
      ([mode, m]) =>
        `| ${mode} | ${pct(m.hitAt1)} | ${pct(m.hitAt3)} | ${m.mrr.toFixed(2)} |`,
    ),
    '',
    '## Misses (relevant chunk not in the top 3)',
    '',
    ...[...results].flatMap(([mode, m]) => [
      `**${mode}**${m.misses.length === 0 ? ': none' : ''}`,
      '',
      ...m.misses.map((q) => `- ${q}`),
      ...(m.misses.length > 0 ? [''] : []),
    ]),
  ];
  mkdirSync(join(REPORT, '..'), { recursive: true });
  writeFileSync(REPORT, lines.join('\n'));
}
